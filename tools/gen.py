"""Builds fasthtmlparser_pure/_tables.py from the C# sources of z3l.FastHtmlParser, so that the Python port uses
exactly the same tag list and HTML5 entity table.

    python tools/gen.py ../z3l.FastHtmlParser/src/z3l.FastHtmlParser
"""

import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "fasthtmlparser_pure" / "_tables.py"


def read(path):
    return Path(path).read_bytes().decode("utf-8").replace("\r\n", "\n")


def enum_members(path, name):
    """The member names of a C# enum without explicit values, in order."""
    text = read(path)
    body = text[text.index(f"public enum {name}"):]
    body = body[body.index("{") + 1:body.rindex("}")]
    out = []
    for line in body.split("\n"):
        line = re.sub(r"//.*", "", line).strip().rstrip(",").strip()
        if line:
            out.append(line)
    return out


def tags(src):
    special = {"Comment": "!--", "Doctype": "!doctype", "XmlDeclaration": "?xml"}
    names = []
    for m in enum_members(Path(src) / "HtmlTag.cs", "HtmlTag"):
        name = special.get(m, m.lower())
        if name in names:
            raise SystemExit(f"duplicate tag {name}")
        names.append(name)
    return names


def constant_text(text, name):
    """The concatenated string literals of `name = "..." + "...";`, escapes left as written."""
    start = text.index(f"{name} =")
    stop = text.index(";", start)
    return "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', text[start:stop]))


def units(s):
    """C# escapes (\\uXXXX, \\0) into a list of UTF-16 units."""
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            e = s[i + 1]
            if e == "u":
                out.append(int(s[i + 2:i + 6], 16))
                i += 6
                continue
            if e == "0":
                out.append(0)
                i += 2
                continue
            raise SystemExit(f"unexpected escape \\{e}")
        out.append(ord(c))
        i += 1
    return out


def entities(src):
    table = read(Path(src) / "Core" / "HtmlEntities.Table.cs")
    names = constant_text(table, "private const string Names").split()
    us = units(constant_text(table, "private const string Values"))
    if len(us) != 2 * len(names):
        raise SystemExit(f"{len(names)} names, {len(us)} value units")
    out = []
    for i, n in enumerate(names):
        legacy = n.startswith("+")
        name = n[1:] if legacy else n
        a, z = us[2 * i], us[2 * i + 1]
        if z == 0:
            value = chr(a)
        elif 0xD800 <= a <= 0xDBFF:
            value = chr(0x10000 + ((a - 0xD800) << 10) + (z - 0xDC00))
        else:
            value = chr(a) + chr(z)
        out.append((name, value, legacy))
    return out


def main(argv):
    if len(argv) != 1:
        print("usage: python tools/gen.py <path to src/z3l.FastHtmlParser>", file=sys.stderr)
        return 2
    src = argv[0]
    names = tags(src)
    ents = entities(src)
    b = ['"""Code generated by tools/gen.py from HtmlTag.cs and HtmlEntities.Table.cs; DO NOT EDIT."""\n\n']
    b.append("# Known tag names by ordinal (the order of the C# enum).\nTAG_NAMES = (\n")
    b.extend(f"    {n!r},\n" for n in names)
    b.append(")\n\n")
    b.append(f"MAX_NAME = {max(len(n) for n, _, _ in ents)}\n")
    b.append(f"MAX_LEGACY_NAME = {max(len(n) for n, _, legacy in ents if legacy)}\n\n")
    b.append("# The HTML5 named character references: the names without '&' and ';' and their values.\nENTITIES = {\n")
    b.extend(f"    {n!r}: {ascii(v)},\n" for n, v, _ in ents)
    b.append("}\n\n# The legacy names, which are also recognized without ';'.\nLEGACY = frozenset((\n")
    b.extend(f"    {n!r},\n" for n, _, legacy in ents if legacy)
    b.append("))\n")
    OUT.write_text("".join(b), encoding="utf-8", newline="\n")
    print(f"{len(names)} tags, {len(ents)} entities")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
